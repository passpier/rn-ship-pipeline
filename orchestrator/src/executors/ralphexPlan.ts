import type { ExecRequest } from '../executor.ts';
import { fenced, oneLine } from './text.ts';

// A batch of tasks → a ralphex plan file (S8 X9). Task bodies and failure digests go inside
// fenced blocks: ralphex's parser skips fenced code, so nothing in them can become a task
// header or checkbox. Validation commands are listed for Claude to run as feedback; the
// orchestrator re-runs them itself under `rnship sandbox run`, since ralphex never does
// (S8 X8). They're listed bare: Claude's Bash sandbox applies the same denies, and macOS
// refuses a `sandbox-exec` nested inside it.

const TASK_HEADER = /^###\s+(?:Task|Iteration)\s+([^:]+?):\s*(.*)$/;
const CHECKBOX = /^\s*-\s+\[([ xX])\]\s*(.*)$/;
const SECTION_END = /^#{1,2}\s/;
const FENCE = /^\s*(`{3,}|~{3,})/;

export function renderPlan(req: Pick<ExecRequest, 'tasks' | 'failureDigest'>): string {
  const lines = [`# rnship batch: ${req.tasks.map((t) => t.key).join(', ')}`, '', '## Overview', ''];
  lines.push('Generated by rn-ship-pipeline. Do only what each task describes, then commit it on the current branch.');
  if (req.failureDigest) lines.push('', 'The previous attempt failed with:', '', fenced(req.failureDigest));
  req.tasks.forEach((task, i) => {
    lines.push('', `### Task ${i + 1}: ${oneLine(task.title)}`, '');
    if (task.body.trim()) lines.push(fenced(task.body), '');
    lines.push(`- [ ] Implement: ${oneLine(task.title)}`);
    lines.push('- [ ] Run every validation command below and make it pass');
    lines.push(`- [ ] Commit with the message "feat: ${task.key}"`);
  });
  const commands = [...new Set(req.tasks.flatMap((t) => t.validation))];
  lines.push('', '## Validation Commands', '', ...commands.map((c) => `- \`${c}\``), '');
  return lines.join('\n');
}

/** Task numbers (1-based) whose section has checkboxes and all of them ticked. */
export function completedTaskNumbers(plan: string): number[] {
  const sections = new Map<number, { total: number; done: number }>();
  let current: number | undefined;
  let fence: string | undefined;
  for (const line of plan.split('\n')) {
    const marker = FENCE.exec(line)?.[1];
    if (fence) {
      if (marker && marker[0] === fence[0] && marker.length >= fence.length) fence = undefined;
      continue;
    }
    if (marker) {
      fence = marker;
      continue;
    }
    const header = TASK_HEADER.exec(line);
    if (header) {
      current = Number(header[1]);
      sections.set(current, { total: 0, done: 0 });
      continue;
    }
    if (SECTION_END.test(line)) {
      current = undefined;
      continue;
    }
    const box = CHECKBOX.exec(line);
    if (box && current !== undefined) {
      const section = sections.get(current)!;
      section.total++;
      if (box[1] !== ' ') section.done++;
    }
  }
  return [...sections].filter(([, s]) => s.total > 0 && s.done === s.total).map(([n]) => n);
}
